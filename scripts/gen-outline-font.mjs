/**
 * Converts an outline font (TTF/OTF) into the compact TypeScript module the
 * text renderer consumes: one SVG path per glyph in font units, baseline at
 * y = 0, y down. Run with: node scripts/gen-outline-font.mjs
 *
 * The font is rendered in upper case, so lower-case letters are folded onto
 * the capitals at runtime and their glyphs are not emitted. The character set
 * is printable ASCII, the Latin-1 letters and symbols the font has, and the
 * typographic characters UI copy uses.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import opentype from 'opentype.js';

const SRC = 'vendor/grape-nuts/GrapeNuts-Regular.ttf';
const OUT = 'src/text/fonts/grape-nuts.ts';
const NAME = 'grape-nuts';

const font = opentype.parse(readFileSync(SRC).buffer.slice(0));
const upm = font.unitsPerEm;

/** Characters to include, before upper-case folding. */
const wanted = new Set();
for (let c = 32; c <= 126; c++) wanted.add(String.fromCharCode(c));
// Latin-1: the letters, plus the symbols UI copy uses; the rest (¤ ¦ ¨ ª ¬ ¯ ´ ¸ º ¹ ² ³ ¼ ½ ¾ µ ¶) is left out.
for (let c = 0xc0; c <= 0xff; c++) wanted.add(String.fromCharCode(c));
for (const ch of '\u00a1\u00a2\u00a3\u00a5\u00a7\u00a9\u00ab\u00ae\u00b0\u00b1\u00b7\u00bb\u00bf') wanted.add(ch);
for (const ch of '\u2018\u2019\u201a\u201c\u201d\u201e\u2013\u2014\u2026\u2022\u2039\u203a\u2122\u20ac\u2190\u2191\u2192\u2193\u2713\u00a0')
  wanted.add(ch);

/**
 * Drops line-to points that sit within `tolerance` font units of the segment
 * between their neighbours (invisible at any size the UI uses), which
 * handwriting outlines have in abundance.
 */
function simplify(commands, tolerance = 2.5) {
  const out = [];
  for (let i = 0; i < commands.length; i++) {
    const c = commands[i];
    const prev = out.at(-1);
    const next = commands[i + 1];
    if (
      c.type === 'L' &&
      prev &&
      next &&
      next.type === 'L' &&
      (prev.type === 'L' || prev.type === 'M' || prev.type === 'Q' || prev.type === 'C')
    ) {
      const dx = next.x - prev.x;
      const dy = next.y - prev.y;
      const len = Math.hypot(dx, dy) || 1;
      const dist = Math.abs((c.x - prev.x) * dy - (c.y - prev.y) * dx) / len;
      const t = ((c.x - prev.x) * dx + (c.y - prev.y) * dy) / (len * len);
      if (dist <= tolerance && t >= 0 && t <= 1) continue;
    }
    out.push(c);
  }
  return out;
}

/** Absolute commands as relative ones with integer coordinates: the shortest SVG path data for the same shape. */
function compactPath(commands) {
  let d = '';
  let x = 0;
  let y = 0;
  const n = (v) => Math.round(v);
  const rel = (...pairs) => pairs.map(([px, py]) => `${n(px - x)} ${n(py - y)}`).join(' ');
  for (const c of commands) {
    if (c.type === 'M') d += `M${n(c.x)} ${n(c.y)}`;
    else if (c.type === 'L') {
      if (n(c.x) === x && n(c.y) === y) continue;
      d += `l${rel([c.x, c.y])}`;
    } else if (c.type === 'Q') d += `q${rel([c.x1, c.y1], [c.x, c.y])}`;
    else if (c.type === 'C') d += `c${rel([c.x1, c.y1], [c.x2, c.y2], [c.x, c.y])}`;
    else if (c.type === 'Z') {
      d += 'z';
      continue;
    }
    x = n(c.x);
    y = n(c.y);
  }
  return d.replace(/ -/g, '-');
}

/** The character a glyph is stored under: capitals only. */
const fold = (ch) => {
  const up = ch.toUpperCase();
  return [...up].length === 1 ? up : ch;
};

const glyphs = {};
let maxAscent = 0;
let maxDescent = 0;
for (const raw of [...wanted].toSorted()) {
  const ch = raw === '\u00a0' ? ' ' : fold(raw);
  if (glyphs[ch]) continue;
  const glyph = font.charToGlyph(ch);
  if (!glyph || glyph.index === 0 || glyph.unicode === undefined) continue;
  const path = glyph.getPath(0, 0, upm);
  const d = compactPath(simplify(path.commands));
  const box = path.getBoundingBox();
  if (d) {
    maxAscent = Math.max(maxAscent, -box.y1);
    maxDescent = Math.max(maxDescent, box.y2);
  }
  glyphs[ch] = [Math.round(glyph.advanceWidth), d];
}

const capHeight = font.tables.os2.sCapHeight ?? -font.charToGlyph('H').getPath(0, 0, upm).getBoundingBox().y1;
const entries = Object.entries(glyphs)
  .map(([ch, [advance, d]]) => `  ${JSON.stringify(ch)}: [${advance}, ${JSON.stringify(d)}],`)
  .join('\n');

writeFileSync(
  OUT,
  `// GENERATED by scripts/gen-outline-font.mjs from ${SRC}. Do not edit.
//
// Grape Nuts, copyright 2003 The Grape Nuts Project Authors
// (https://github.com/googlefonts/grapenuts), licensed under the SIL Open
// Font License 1.1. See vendor/grape-nuts/OFL.txt.
import type { StrokeFontData } from '../font.js';

export const GRAPE_NUTS: StrokeFontData = {
  name: '${NAME}',
  kind: 'outline',
  uppercase: true,
  unitsPerEm: ${upm},
  ascent: ${Math.round(maxAscent)},
  descent: ${Math.round(maxDescent)},
  capHeight: ${Math.round(capHeight)},
  glyphs: {
${entries}
  },
};
`,
);
console.log(
  `wrote ${OUT}: ${Object.keys(glyphs).length} glyphs, ascent ${Math.round(maxAscent)}, descent ${Math.round(maxDescent)}, capHeight ${capHeight}`,
);
